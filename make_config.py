"""Writes a training config derived from a base config (used by train_full_coco.sh).

    python make_config.py --base configs/rtdetr_mamba_r50_cocominitrain_v2.yaml --out configs/generated/x.yaml \
        --data data/coco --train-ann instances_train2017.json --fusion mamba --epochs 72 --lr-drop 60 --batch 20

--lr sets the base, Mamba (= base, v2) and backbone (= base / 10) learning rates together; train.py --lr changes only
the base rate.
"""
import argparse
import os

import yaml


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--data", required=True, help="COCO root with train2017/, val2017/, annotations/")
    ap.add_argument("--train-ann", default="instances_train2017.json", help="file in <data>/annotations/")
    ap.add_argument("--fusion", choices=("mamba", "repc3"), default="mamba")
    ap.add_argument("--epochs", type=int, required=True)
    ap.add_argument("--lr-drop", default="", help="comma-separated epochs (empty: no drop)")
    ap.add_argument("--batch", type=int, required=True, help="per GPU")
    ap.add_argument("--lr", type=float, default=None)
    ap.add_argument("--workers", type=int, default=None)
    ap.add_argument("--output-dir", required=True)
    a = ap.parse_args()

    with open(a.base, encoding="utf-8") as f:
        cfg = yaml.safe_load(f)
    data = os.path.abspath(a.data)
    cfg["data"].update(train_img_dir=os.path.join(data, "train2017"),
                       train_ann_file=os.path.join(data, "annotations", a.train_ann),
                       val_img_dir=os.path.join(data, "val2017"),
                       val_ann_file=os.path.join(data, "annotations", "instances_val2017.json"),
                       batch_size=a.batch)
    if a.workers is not None:
        cfg["data"]["num_workers"] = a.workers
    cfg["model"]["encoder"]["fusion"] = a.fusion
    t = cfg["training"]
    t["epochs"] = a.epochs
    t["lr_drop"] = [int(x) for x in a.lr_drop.split(",") if x.strip()]
    if a.lr is not None:
        t["lr"], t["lr_mamba"], t["lr_backbone"] = a.lr, a.lr, a.lr / 10
    cfg["output_dir"] = a.output_dir
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# generated by make_config.py from {a.base}\n")
        yaml.safe_dump(cfg, f, sort_keys=False)
    print(f"{a.out}: fusion {a.fusion}, {a.epochs} epochs, lr_drop {t['lr_drop']}, batch {a.batch}/GPU, "
          f"lr {t['lr']} (mamba {t['lr_mamba']}, backbone {t['lr_backbone']}), data {data}")


if __name__ == "__main__":
    main()
